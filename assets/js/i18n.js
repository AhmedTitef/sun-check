export function pickLang() {
  try { const saved = localStorage.getItem('suncheck.lang'); if (saved === 'en' || saved === 'es') return saved; } catch (e) { /* ignore */ }
  return /^es\b/i.test(navigator.language || '') ? 'es' : 'en';
}

export function makeT(lang) {
  const dict = STR[lang] || STR.en;
  return (key, vars = {}) => {
    let s = key.split('.').reduce((o, k) => (o ? o[k] : undefined), dict);
    if (s == null) s = key.split('.').reduce((o, k) => (o ? o[k] : undefined), STR.en);
    if (typeof s !== 'string') return s;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  };
}
